// Minimal, dependency-free CSV parser — deliberately not using the `xlsx`
// npm package, which has two unpatched high-severity advisories (prototype
// pollution, ReDoS) with no fix available. This app's own "Download
// template" already generates plain CSV (see ExcelUpload.jsx's downloadCsv),
// so real upload parsing only ever needs to read that same format back —
// no binary .xlsx parsing, no regex-based tokenizing, just a plain
// character-by-character state machine over a handful of KB of text.
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;

  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];
    if (inQuotes) {
      if (char === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 1;
        } else {
          inQuotes = false;
        }
      } else {
        field += char;
      }
    } else if (char === '"') {
      inQuotes = true;
    } else if (char === ',') {
      row.push(field);
      field = '';
    } else if (char === '\n' || char === '\r') {
      if (char === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else {
      field += char;
    }
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }

  return rows.filter((r) => r.some((cell) => cell.trim() !== ''));
}
